# v6.6 style fields
# v6.6 风格字段
# ============================================================
def _collect_v66_style_fields(
    sample: dict[str, Any],
    *,
    require_v66_style_fields: bool,
) -> dict[str, Any]:
    require = bool(require_v66_style_fields)
    out: dict[str, Any] = {}

    prompt_acoustic = _ensure_optional_2d_float(sample, "prompt_acoustic", require=require)
    if prompt_acoustic is not None:
        prompt_acoustic_len = _normalize_optional_length(
            sample.get("prompt_acoustic_lengths", None),
            fallback=int(prompt_acoustic.shape[0]),
        )
        prompt_acoustic_len = min(prompt_acoustic_len, int(prompt_acoustic.shape[0]))
        prompt_acoustic = prompt_acoustic[:prompt_acoustic_len]
        out["prompt_acoustic"] = prompt_acoustic
        out["prompt_acoustic_lengths"] = int(prompt_acoustic_len)
    elif require:
        raise KeyError("Missing prompt_acoustic")

    target_energy = _ensure_optional_1d_float(sample, "target_energy", require=require)
    if target_energy is not None:
        out["target_energy"] = target_energy

    prompt_energy = _ensure_optional_1d_float(sample, "prompt_energy", require=require)
    if prompt_energy is not None:
        out["prompt_energy"] = prompt_energy

    target_f0 = _ensure_optional_1d_float(sample, "target_f0", require=False)
    if target_f0 is not None:
        out["target_f0"] = target_f0

    prompt_f0 = _ensure_optional_1d_float(sample, "prompt_f0", require=False)
    if prompt_f0 is not None:
        out["prompt_f0"] = prompt_f0

    if "target_f0_voiced_mask" in sample:
        out["target_f0_voiced_mask"] = sample["target_f0_voiced_mask"].detach().cpu().bool().reshape(-1)

    if "prompt_f0_voiced_mask" in sample:
        out["prompt_f0_voiced_mask"] = sample["prompt_f0_voiced_mask"].detach().cpu().bool().reshape(-1)

    if "target_speaker_embedding" in sample:
        out["target_speaker_embedding"] = sample["target_speaker_embedding"].detach().cpu().float().reshape(-1)
    if "prompt_speaker_embedding" in sample:
        out["prompt_speaker_embedding"] = sample["prompt_speaker_embedding"].detach().cpu().float().reshape(-1)

    if "v66_style_cache_meta" in sample:
        out["v66_style_cache_meta"] = sample.get("v66_style_cache_meta")

    return out


