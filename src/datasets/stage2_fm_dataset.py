V66_STYLE_REQUIRED_KEYS = [
    "prompt_acoustic",
    "prompt_acoustic_lengths",
    "target_energy",
    "prompt_energy",
]


class Stage2FMDataset(Dataset):
    """
    EN:
    Minimal dataset for stage-2 Flow Matching training.

    v6.6.0-B:
        This dataset still keeps the original v6.5 behaviour by default, but it
        can optionally require v6.6 style-cache fields generated by
        scripts/export_fewshot_style_cache.py.

    ZH:
    第二阶段 Flow Matching 训练数据集。

    v6.6.0-B:
        默认保持原 v6.5 行为，同时可选要求由
        scripts/export_fewshot_style_cache.py 生成的 v6.6 风格字段。
    """

    def __init__(
        self,
        data_root: str | Path,
        *,
        require_stage1_pred_semantic: bool = False,
        require_v66_style_fields: bool = False,
    ) -> None:
        self.data_root = Path(data_root).resolve()
        self.require_stage1_pred_semantic = bool(require_stage1_pred_semantic)
        self.require_v66_style_fields = bool(require_v66_style_fields)

        if not self.data_root.exists():
            raise FileNotFoundError(f"Dataset root not found: {self.data_root}")

        self.sample_files = sorted(self.data_root.glob("*.pt"))
        if not self.sample_files:
            raise FileNotFoundError(f"No .pt sample files found under: {self.data_root}")

    def __len__(self) -> int:
        return len(self.sample_files)

    def __getitem__(self, index: int) -> dict[str, Any]:
        sample_path = self.sample_files[index]
        sample = torch.load(sample_path, map_location="cpu", weights_only=False)

        if not isinstance(sample, dict):
            raise TypeError(f"Expected sample dict from {sample_path}, got {type(sample)}")

        required_keys = [
            "semantic_tokens",
            "bert_feature",
            "prompt_tokens",
            "target_acoustic",
            "phoneme_ids",
            "phoneme_lens",
            "raw_text",
            "norm_text",
            "language",
            "sample_id",
            "prompt_wav_path",
            "target_wav_path",
        ]

        for key in required_keys:
            if key not in sample:
                raise KeyError(f"Sample {sample_path} missing required key: {key}")

        if self.require_stage1_pred_semantic and "stage1_pred_semantic_tokens" not in sample:
            raise KeyError(
                f"Sample {sample_path} missing required key: stage1_pred_semantic_tokens"
            )

        if self.require_v66_style_fields:
            for key in V66_STYLE_REQUIRED_KEYS:
                if key not in sample:
                    raise KeyError(
                        f"Sample {sample_path} missing v6.6 style-cache key: {key}. "
                        "Please run scripts/export_fewshot_style_cache.py first."
                    )

        sample["__source_file__"] = str(sample_path)
        return sample


