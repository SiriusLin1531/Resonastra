def _pad_1d_float_feature_dim(
    seqs: list[torch.Tensor],
    *,
    feature_dim: int | None = None,
) -> torch.Tensor:
    if not seqs:
        return torch.empty(0, int(feature_dim or 0), dtype=torch.float32)

    normalized: list[torch.Tensor] = []
    dim = int(feature_dim or 0)
    for x in seqs:
        y = x.detach().cpu().float().reshape(-1)
        if dim <= 0:
            dim = int(y.numel())
        if int(y.numel()) != dim:
            raise ValueError(f"speaker embedding dim mismatch: got {y.numel()}, expected {dim}")
        normalized.append(y)
    return torch.stack(normalized, dim=0).contiguous()

