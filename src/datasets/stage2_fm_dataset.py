def _validate_semantic_source_args(
    semantic_source_mode: str,
    semantic_oracle_prob: float,
) -> tuple[str, float]:
    mode = str(semantic_source_mode).strip().lower()
    if mode not in SEMANTIC_SOURCE_MODES:
        raise ValueError(
            f"semantic_source_mode must be one of {sorted(SEMANTIC_SOURCE_MODES)}, "
            f"got {semantic_source_mode!r}"
        )

    prob = float(semantic_oracle_prob)
    if not (0.0 <= prob <= 1.0):
        raise ValueError(f"semantic_oracle_prob must be in [0,1], got {prob}")

    return mode, prob


def _semantic_source_to_id(name: str) -> int:
    return int(SEMANTIC_SOURCE_TO_ID.get(str(name), -1))


def _safe_length_from_tokens(tokens: torch.Tensor | None) -> int:
    if tokens is None or not torch.is_tensor(tokens) or tokens.ndim == 0:
        return 0
    return int(tokens.reshape(-1).shape[0])


def _compute_semantic_reliability(
    *,
    selected_source: str,
    oracle_len: int,
    pred_len: int,
) -> float:
    if selected_source == "oracle":
        return 1.0
    if selected_source == "predicted":
        if oracle_len <= 0 or pred_len <= 0:
            return 0.5
        ratio = float(pred_len) / max(float(oracle_len), 1.0)
        # Gentle prior: closer length ratio -> higher reliability.
        return float(max(0.0, min(1.0, 1.0 - abs(ratio - 1.0))))
    return 0.0


def _choose_semantic_source(
    *,
    sample: dict[str, Any],
    semantic_source_mode: str,
    semantic_oracle_prob: float,
) -> str:
    mode, prob = _validate_semantic_source_args(
        semantic_source_mode=semantic_source_mode,
        semantic_oracle_prob=semantic_oracle_prob,
    )

    if mode == "oracle":
        return "oracle"
    if mode == "predicted":
        return "predicted"

    return "oracle" if random.random() < prob else "predicted"


def _get_selected_semantic_tokens(
    *,
    sample: dict[str, Any],
    semantic_source_mode: str,
    semantic_oracle_prob: float,
) -> tuple[torch.LongTensor, int, str, int, float]:
    selected_source = _choose_semantic_source(
        sample=sample,
        semantic_source_mode=semantic_source_mode,
        semantic_oracle_prob=semantic_oracle_prob,
    )

    oracle_tokens = _ensure_1d_long(sample["semantic_tokens"], "semantic_tokens")
    oracle_len = _normalize_optional_length(
        sample.get("semantic_lengths", None),
        fallback=int(oracle_tokens.shape[0]),
    )
    oracle_len = min(oracle_len, int(oracle_tokens.shape[0]))

    pred_len = 0
    if "stage1_pred_semantic_tokens" in sample:
        pred_tokens_for_len = _ensure_1d_long(
            sample["stage1_pred_semantic_tokens"],
            "stage1_pred_semantic_tokens",
        )
        pred_len = _normalize_optional_length(
            sample.get("stage1_pred_semantic_lengths", None),
            fallback=int(pred_tokens_for_len.shape[0]),
        )
        pred_len = min(pred_len, int(pred_tokens_for_len.shape[0]))

    if selected_source == "oracle":
        tokens = oracle_tokens[:oracle_len]
        length = int(oracle_len)
    elif selected_source == "predicted":
        if "stage1_pred_semantic_tokens" not in sample:
            raise KeyError(
                "semantic_source_mode selected predicted semantic, but sample is missing "
                "stage1_pred_semantic_tokens."
            )
        tokens = _ensure_1d_long(
            sample["stage1_pred_semantic_tokens"],
            "stage1_pred_semantic_tokens",
        )
        length = _normalize_optional_length(
            sample.get("stage1_pred_semantic_lengths", None),
            fallback=int(tokens.shape[0]),
        )
        length = min(length, int(tokens.shape[0]))
        tokens = tokens[:length]
    else:
        raise ValueError(f"Unsupported selected_source={selected_source!r}")

    source_id = _semantic_source_to_id(selected_source)
    reliability = _compute_semantic_reliability(
        selected_source=selected_source,
        oracle_len=int(oracle_len),
        pred_len=int(pred_len),
    )

    return tokens.contiguous().long(), int(length), selected_source, int(source_id), float(reliability)


