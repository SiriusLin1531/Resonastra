def _pad_1d_long(seqs: list[torch.Tensor], pad_value: int = 0) -> torch.Tensor:
    return pad_sequence(
        [_ensure_1d_long(x, "seq") for x in seqs],
        batch_first=True,
        padding_value=pad_value,
    )


def _pad_optional_1d_long(
    seqs: list[torch.Tensor],
    *,
    pad_value: int = 0,
    min_width: int = 1,
) -> torch.Tensor:
    normalized: list[torch.Tensor] = []
    max_len = 0

    for x in seqs:
        if not torch.is_tensor(x):
            x = torch.empty(0, dtype=torch.long)
        y = x.detach().cpu().long().reshape(-1)
        normalized.append(y)
        max_len = max(max_len, int(y.numel()))

    max_len = max(max_len, int(min_width), 1)
    out = torch.full((len(normalized), max_len), int(pad_value), dtype=torch.long)

    for i, y in enumerate(normalized):
        if y.numel() > 0:
            out[i, : y.numel()] = y

    return out


def _pad_bert_features(feats: list[torch.Tensor]) -> torch.Tensor:
    batch_size = len(feats)
    channels = int(feats[0].shape[0])
    max_len = max(int(x.shape[1]) for x in feats)

    out = torch.zeros(batch_size, channels, max_len, dtype=feats[0].dtype)
    for i, feat in enumerate(feats):
        out[i, :, : feat.shape[1]] = feat
    return out


def _pad_acoustic(xs: list[torch.Tensor]) -> torch.Tensor:
    batch_size = len(xs)
    feat_dim = int(xs[0].shape[1])
    max_len = max(int(x.shape[0]) for x in xs)

    out = torch.zeros(batch_size, max_len, feat_dim, dtype=xs[0].dtype)
    for i, x in enumerate(xs):
        out[i, : x.shape[0], :] = x
    return out


def _pad_2d_float(
    seqs: list[torch.Tensor],
    *,
    pad_value: float = 0.0,
    min_width: int = 1,
    feature_dim: int | None = None,
) -> torch.Tensor:
    normalized: list[torch.Tensor] = []
    inferred_dim = feature_dim
    max_len = 0

    for x in seqs:
        if not torch.is_tensor(x):
            if inferred_dim is None:
                inferred_dim = 1
            x = torch.empty(0, int(inferred_dim), dtype=torch.float32)

        y = x.detach().cpu().float()
        if y.ndim == 3 and y.shape[0] == 1:
            y = y.squeeze(0)
        if y.ndim != 2:
            raise ValueError(f"Expected 2D tensor, got {tuple(y.shape)}")

        if inferred_dim is None:
            inferred_dim = int(y.shape[1])
        elif int(y.shape[1]) != int(inferred_dim):
            raise ValueError(f"Feature dim mismatch: expected {inferred_dim}, got {y.shape[1]}")

        normalized.append(y.contiguous())
        max_len = max(max_len, int(y.shape[0]))

    if inferred_dim is None:
        inferred_dim = 1

    max_len = max(max_len, int(min_width), 1)
    out = torch.full(
        (len(normalized), max_len, int(inferred_dim)),
        float(pad_value),
        dtype=torch.float32,
    )

    for i, y in enumerate(normalized):
        if y.shape[0] > 0:
            out[i, : y.shape[0], :] = y

    return out


