def create_stage2_fm_collate_fn(
    *,
    semantic_source_mode: str = "oracle",
    semantic_oracle_prob: float = 0.5,
    include_continuous_semantic: bool = False,
    require_continuous_semantic: bool = False,
    continuous_semantic_dim: int = 768,
    include_v66_style_fields: bool = True,
    require_v66_style_fields: bool = False,
) -> Callable[[list[dict[str, Any]]], Stage2Inputs]:
    mode, prob = _validate_semantic_source_args(
        semantic_source_mode=semantic_source_mode,
        semantic_oracle_prob=semantic_oracle_prob,
    )

    def _collate(samples: list[dict[str, Any]]) -> Stage2Inputs:
        return stage2_fm_collate_fn_with_semantic_source(
            samples,
            semantic_source_mode=mode,
            semantic_oracle_prob=prob,
            include_continuous_semantic=bool(include_continuous_semantic),
            require_continuous_semantic=bool(require_continuous_semantic),
            continuous_semantic_dim=int(continuous_semantic_dim),
            include_v66_style_fields=bool(include_v66_style_fields),
            require_v66_style_fields=bool(require_v66_style_fields),
        )

    return _collate


def _move_to_device_recursive(value: Any, device: torch.device) -> Any:
    if isinstance(value, torch.Tensor):
        return value.to(device, non_blocking=True)
    if isinstance(value, dict):
        return {k: _move_to_device_recursive(v, device) for k, v in value.items()}
    if isinstance(value, list):
        return [_move_to_device_recursive(v, device) for v in value]
    if isinstance(value, tuple):
        return tuple(_move_to_device_recursive(v, device) for v in value)
    return value


def move_stage2_inputs_to_device(batch: Stage2Inputs, device: torch.device) -> Stage2Inputs:
    """
    EN:
    Move tensor fields and tensor values inside extras to target device.

    ZH:
    将 Stage2Inputs 主字段和 extras 内的 tensor 递归移动到目标 device。
    """
    kwargs: dict[str, Any] = {}

    for f in fields(Stage2Inputs):
        value = getattr(batch, f.name)
        kwargs[f.name] = _move_to_device_recursive(value, device)

    return Stage2Inputs(**kwargs)
