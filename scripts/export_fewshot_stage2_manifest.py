def str2bool(x: str | bool) -> bool:
    """
    EN:
    Convert common string values to bool.

    ZH:
    将常见字符串形式转换为 bool。
    """
    if isinstance(x, bool):
        return x

    s = str(x).strip().lower()

    if s in {"1", "true", "yes", "y", "on"}:
        return True

    if s in {"0", "false", "no", "n", "off"}:
        return False

    raise argparse.ArgumentTypeError(f"Cannot parse boolean value from: {x}")


